language.Add("Cleanup_db_buildings","Dynamic Buildings")
language.Add("Cleaned_db_buildings","Removed Dynamic Buildings")
hook.Add("PopulateToolMenu","DB.Settings",function()
    spawnmenu.AddToolMenuOption("Utilities","User","DBSettings","Dynamic Buildings","","",function(p)
        p:Help("Gas Station: Entities > Dynamic Buildings. Requires the building models pack.")
        p:Help("Server settings; changes affect future visits. Traffic is experimental.")
        p:Help("Car visits have their own two-bay budget: server console db_cars 0..2 (default 2).")
        p:Help("Admins can change the settings below. Other players can view the panel.")
        local slider=p:NumSlider("Maximum walk-in customers",nil,0,4,0)
        slider:SetValue(GetConVar("db_customers") and GetConVar("db_customers"):GetInt() or 2)
        local traffic=p:CheckBox("Experimental car visits",nil)
        traffic:SetValue(GetConVar("db_traffic") and GetConVar("db_traffic"):GetBool() or false)
        local function send()
            timer.Create("DB.SettingsDebounce",0.35,1,function()
                if not IsValid(slider) or not IsValid(traffic) or not LocalPlayer():IsAdmin() then return end
                net.Start("db_settings") net.WriteUInt(math.Clamp(math.Round(slider:GetValue()),0,4),3)
                net.WriteBool(traffic:GetChecked()) net.SendToServer()
            end)
        end
        slider.OnValueChanged=send traffic.OnChange=send
    end)
end)
